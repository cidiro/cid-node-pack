import os
import logging
import numpy as np
from PIL import Image
import torch
import json

logger = logging.getLogger('cid_node_pack')
logger.setLevel(logging.WARNING)


class CidLoadImageFromDir:
    """Loads images from a directory with various sorting and selection options."""
    
    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                "directory": ("STRING", {
                    "default": "",
                    "tooltip": "Path to the directory containing images to load. Can be absolute or relative to ComfyUI installation."
                }),
                "sort_by": (["a-z", "z-a", "last modified", "first modified"], {
                    "default": "a-z",
                    "tooltip": "Determines the order of images: alphabetically (a-z/z-a) or by modification time (newest/oldest first)."
                }),
                "index": ("INT", {
                    "default": 0, 
                    "min": 0, 
                    "max": 0xffffffffffffffff,
                    "tooltip": "Index of the image to load. Can be given a random value generated by a seed generator node, and it will be converted to a valid index."
                }),
                "include_subdirectories": ("BOOLEAN", {
                    "default": False,
                    "tooltip": "When enabled, images from all subdirectories will also be included in the available pool."
                }),
                "remember_loaded_images": ("BOOLEAN", {
                    "default": False, 
                    "tooltip": "When enabled, keeps track of which images have been loaded and excludes them from future selections. When disabled, the history is cleared when the node is reloaded."
                }),
            }
        }

    RETURN_TYPES = ("IMAGE", "STRING")
    RETURN_NAMES = ("image", "file_path")
    FUNCTION = "main"
    CATEGORY = "Cid Node Pack/IO"

    def __init__(self):
        # Last loaded index - storing this allows for proper operation of increment/decrement
        self.last_index = 0
        # Last seen file count - helps detect when directory content changes
        self.last_file_count = 0
        # Cache of sorted files to avoid re-scanning directory unnecessarily
        self.cached_files = []
        # Last directory and sort settings - used to determine when to refresh the cache
        self.last_directory = ""
        self.last_sort_by = ""
        self.last_include_subdirs = False
        # Previously loaded images tracking
        self.history_file = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 
                                       "resources", "load_image_history.json")
        self.loaded_images = self._load_history()

    def _load_history(self):
        """Load the history of loaded images from file"""
        if os.path.exists(self.history_file):
            try:
                with open(self.history_file, 'r') as f:
                    return json.load(f)
            except Exception as e:
                error_msg = f"Failed to load image history: {str(e)}"
                logger.error(error_msg)
                raise Exception(error_msg)
        return {}

    def _save_history(self):
        """Save the history of loaded images to file"""
        try:
            with open(self.history_file, 'w') as f:
                json.dump(self.loaded_images, f, indent=4, sort_keys=True)
        except Exception as e:
            error_msg = f"Failed to save image history: {str(e)}"
            logger.error(error_msg)
            raise Exception(error_msg)

    def _reset_history(self, directory):
        """Reset the history of loaded images for a specific directory"""
        self.loaded_images[directory] = []
        self._save_history()
        logger.info(f"Image load history has been reset for directory: {directory}")

    def _get_sorted_files(self, directory, sort_by, include_subdirs, exclude_loaded=False):
        """Get a list of image files from directory, sorted according to sort_by.
        If exclude_loaded is True, files that have been loaded previously will be excluded.
        """

        # If we can use cache and we're not excluding loaded files, use the cache
        if (directory == self.last_directory and 
            sort_by == self.last_sort_by and
            include_subdirs == self.last_include_subdirs and
            len(self.cached_files) > 0 and
            not exclude_loaded):
            return self.cached_files

        supported_extensions = ['.png', '.jpg', '.jpeg', '.webp', '.bmp', '.tiff', '.tif']
        image_extensions = tuple(supported_extensions)

        # Get previously loaded files for this directory if excluding them
        previously_loaded = set()
        if exclude_loaded and directory in self.loaded_images:
            previously_loaded = set(self.loaded_images[directory])
            logger.info(f"Found {len(previously_loaded)} previously loaded images for directory: {directory}")

        # Collect all image files
        image_files = []
        if include_subdirs:
            for root, _, files in os.walk(directory):
                for file in files:
                    if file.lower().endswith(image_extensions):
                        full_path = os.path.join(root, file)
                        rel_path = os.path.relpath(full_path, directory)
                        
                        if not exclude_loaded or rel_path not in previously_loaded:
                            image_files.append(full_path)
        else:
            for file in os.listdir(directory):
                if file.lower().endswith(image_extensions):
                    full_path = os.path.join(directory, file)
                    
                    if not exclude_loaded or file not in previously_loaded:
                        image_files.append(full_path)

        # Sort files
        if sort_by == "a-z":
            image_files.sort()
        elif sort_by == "z-a":
            image_files.sort(reverse=True)
        elif sort_by == "last modified":
            image_files.sort(key=os.path.getmtime, reverse=True)
        elif sort_by == "first modified":
            image_files.sort(key=os.path.getmtime)
            
        # Only update cache if we're not excluding loaded files
        if not exclude_loaded:
            self.cached_files = image_files
            self.last_directory = directory
            self.last_sort_by = sort_by
            self.last_include_subdirs = include_subdirs
            self.last_file_count = len(image_files)
            
        logger.info(f"Found {len(image_files)} image(s) in directory: {directory}" + 
                  (f" (excluding {len(previously_loaded)} previously loaded)" if exclude_loaded else ""))
            
        return image_files

    def main(self, directory, sort_by, index, include_subdirectories, remember_loaded_images):
        """Load an image from the directory based on index and control settings."""
        
        # Ensure directory is valid
        if not directory or not os.path.isdir(directory):
            error_msg = f"Invalid directory: {directory}"
            logger.error(error_msg)
            raise Exception(error_msg)

        # Handle history tracking toggle
        if not remember_loaded_images and directory in self.loaded_images:
            self._reset_history(directory)
        
        # Get the sorted list of image files
        image_files = self._get_sorted_files(directory, sort_by, include_subdirectories, 
                                            exclude_loaded=remember_loaded_images)
        
        if remember_loaded_images and not image_files:
            error_msg = f"All images in '{directory}' have already been loaded. Disable 'remember_loaded_images' to reset the history and load images again."
            logger.error(error_msg)
            raise Exception(error_msg)
        
        if not image_files:
            error_msg = f"No valid image files found in directory: {directory}"
            logger.error(error_msg)
            raise Exception(error_msg)
            
        # Use index to determine index
        num_images = len(image_files)
        image_index = index % num_images
        
        logger.info(f"Using index {index} to select image {image_index} of {num_images}")
        
        # Load the image
        image_path = image_files[image_index]
        try:
            # Track this image path if history is enabled
            if remember_loaded_images:
                if directory not in self.loaded_images:
                    self.loaded_images[directory] = []
                
                rel_path = os.path.relpath(image_path, directory)
                if rel_path not in self.loaded_images[directory]:
                    self.loaded_images[directory].append(rel_path)
                    self._save_history()
                    logger.info(f"Added image to history: {rel_path} (in {directory})")
            
            pil_image = Image.open(image_path).convert('RGB')
            
            image_np = np.array(pil_image).astype(np.float32) / 255.0
            image_tensor = torch.from_numpy(image_np).unsqueeze(0)
            
            logger.info(f"Loaded image: {image_path}")
            return (image_tensor, image_path)
            
        except Exception as e:
            error_msg = f"Failed to load image at index {image_index} (file '{os.path.abspath(image_path)}'): {str(e)}"
            logger.error(error_msg)
            raise Exception(error_msg)
